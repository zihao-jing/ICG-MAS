"""Run the R2 and R6 setup gates over the frozen E4 artifacts (no model call).

R2 delivery: would the extraction/insertion repair text have been rejected
before its answer call? R6 matcher: how many selection cases survive the
faithful-carrier rule, and how many distortion swaps carry the distorted fact?

    ./run.sh python -m scripts.check_e4_gates
"""
import json
from pathlib import Path

from src.audit.e4_fix_gates import delivery_gate, distortion_gate, selection_eligible

ROOT = Path(__file__).resolve().parent.parent
P1 = ROOT / 'rebuttal/pilots/20261110_e4_phase1/actions_phase1.json'
P23 = ROOT / 'rebuttal/pilots/20261111_e4_phase23/actions_phase23.json'
PLAN = ROOT / 'rebuttal/pilots/20261110_e4_insert/insertion_plan.json'
RAW1 = ROOT / 'rebuttal/results/batch1/E4_phase1/raw'
RAWI = ROOT / 'rebuttal/results/batch1/E4_direct_insertion/raw'
MATCHER = ROOT / 'rebuttal/results/batch1/E4_pool_matcher/matcher'
OUT = ROOT / 'rebuttal/diagnosis/gates_preflight.md'
OUT_JSON = ROOT / 'rebuttal/diagnosis/gates_preflight.json'


def load_raw(d):
    out = {}
    for f in sorted(d.glob('*.json')):
        recs = json.loads(f.read_text())
        if not recs or 'trace_id' not in recs[0]:
            continue
        out[recs[0]['trace_id']] = {r['arm']: r for r in recs if r.get('arm')}
    return out


def main():
    rows = [r for r in json.loads(P1.read_text()) if r['group'] == 'extraction_omission']
    plan = {p['trace_id']: p for p in json.loads(PLAN.read_text())['cases']}
    raw, insraw = load_raw(RAW1), load_raw(RAWI)
    delivery = {'R-ext': [], 'R-ins': []}
    for r in rows:
        fact = plan[r['trace_id']]['repair_unit']['text']
        for arm, rawmap in (('R-ext', raw), ('R-ins', insraw)):
            rec = rawmap.get(r['trace_id'], {}).get(arm)
            if not rec:
                continue
            units = ([u['text'] for u in rec.get('added_units') or []]
                     or ([rec['inserted_unit']['text']] if rec.get('inserted_unit') else []))
            text = ' '.join(units)
            g = delivery_gate(text, fact, r['question'])
            g.update(trace_id=r['trace_id'], instance_id=r['instance_id'],
                     model=r['model'], arm=arm)
            delivery[arm].append(g)
    sel = []
    for f in MATCHER.glob('*.json'):
        rec = json.loads(f.read_text())
        carriers = rec.get('carriers') or (rec.get('carrier_call') or {}).get('value')
        if not carriers:
            continue
        eligible = selection_eligible(carriers)
        sel.append({'instance_id': rec['instance_id'], 'model': rec['model'],
                    'diagnosis': rec.get('diagnosis'), 'eligible_fact_ids': eligible})
    dist = []
    for r in json.loads(P23.read_text()):
        if r['group'] != 'distortion':
            continue
        swap_id = r['target_swap']['unit_id']
        facts = {f['fact_id']: f['text'] for f in r['facts']['facts']}
        distorted = {}
        for c in r['carriers']['facts']:
            if any(swap_id in (u.get('unit_ids') or []) and u.get('fidelity') != 'faithful'
                   for u in c['board']):
                distorted[c['fact_id']] = facts[c['fact_id']]
        replaced = next((u['text'] for u in r['board_units'] if u['unit_id'] == swap_id), '')
        g = distortion_gate(r['target_swap']['text'], distorted, replaced)
        g.update(trace_id=r['trace_id'], instance_id=r['instance_id'], n_facts=len(distorted))
        dist.append(g)
    result = {'delivery': delivery, 'selection': sel, 'distortion': dist}
    OUT_JSON.write_text(json.dumps(result, indent=1) + '\n')

    rext_blocked = [g for g in delivery['R-ext'] if not g['ok']]
    rins_blocked = [g for g in delivery['R-ins'] if not g['ok']]
    sel_hits = [s for s in sel if s['eligible_fact_ids']]
    dist_ok = [g for g in dist if g['ok']]
    lines = ['# Gate pre-flight on frozen artifacts\n',
             'Generated by `scripts/check_e4_gates.py`; no model calls.\n',
             '## R2 delivery gate\n',
             f'- R-ext repair texts: {len(delivery["R-ext"])} checked, '
             f'{len(rext_blocked)} would be rejected before the answer call '
             f'({len(delivery["R-ext"]) - len(rext_blocked)} pass).',
             f'- R-ins repair texts: {len(delivery["R-ins"])} checked, '
             f'{len(rins_blocked)} would be rejected '
             f'({len(delivery["R-ins"]) - len(rins_blocked)} pass).',
             '',
             '| arm | case | model | recall | reasons |',
             '| --- | --- | --- | --- | --- |']
    for g in rext_blocked:
        lines.append(f"| {g['arm']} | {g['instance_id']} | {g['model'].split('/')[-1]} | "
                     f"{g['recall']:.3f} | {'; '.join(g['reasons'])} |")
    lines += ['', '## R6 matcher gates\n',
              f'- Selection: {len(sel)} matcher records, '
              f'{len(sel_hits)} with a faithful extraction carrier and no board carrier.',
              f'- Distortion: {len(dist)} swaps, {len(dist_ok)} carry the distorted fact '
              f'(swap recall >= 0.8 and replaced-unit recall >= 0.5).']
    if sel_hits:
        lines.append('')
        lines.append('| selection hit | model | eligible facts |')
        lines.append('| --- | --- | --- |')
        for s in sel_hits:
            lines.append(f"| {s['instance_id']} | {s['model']} | "
                         f"{', '.join(s['eligible_fact_ids'])} |")
    OUT.write_text('\n'.join(lines) + '\n')
    print(json.dumps({'rext_checked': len(delivery['R-ext']), 'rext_blocked': len(rext_blocked),
                      'rins_checked': len(delivery['R-ins']), 'rins_blocked': len(rins_blocked),
                      'selection_records': len(sel), 'selection_hits': len(sel_hits),
                      'distortion_checked': len(dist), 'distortion_pass': len(dist_ok)}))


if __name__ == '__main__':
    main()